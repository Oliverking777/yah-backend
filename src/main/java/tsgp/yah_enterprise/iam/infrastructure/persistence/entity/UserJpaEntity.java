package tsgp.yah_enterprise.iam.infrastructure.persistence.entity;

import java.time.Instant;
import java.util.UUID;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * JPA entity for the "users" table.
 * This is a persistence model only; business rules live in the domain User class.
 * The role is stored as a plain id, with no JPA link to RoleJpaEntity.
 */
@Entity
@Table(name = "users")
@Getter
@Setter
@NoArgsConstructor(access = AccessLevel.PROTECTED) // required by JPA
@AllArgsConstructor
public class UserJpaEntity {

    @Id
    @Column(name = "user_id", nullable = false, updatable = false)
    private UUID userId; // generated by the domain, so no @GeneratedValue

    @Column(name = "first_name", nullable = false, length = 100)
    private String firstName;

    @Column(name = "last_name", nullable = false, length = 100)
    private String lastName;

    @Column(name = "full_name", nullable = false, length = 201)
    private String fullName;

    @Column(name = "username", nullable = false, unique = true, updatable = false, length = 50)
    private String userName;

    @Column(name = "role_id", nullable = false)
    private UUID roleId;

    @Column(name = "active", nullable = false)
    private boolean active;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    // Written only by UserJpaRepository.updateLastActiveAt. updatable = false, so a normal save()
    // can never overwrite it with a stale value.
    @Column(name = "last_active_at", updatable = false)
    private Instant lastActiveAt;
}