package tsgp.yah_enterprise.iam.infrastructure.persistence.entity;

import java.time.Instant;
import java.util.UUID;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * JPA entity for the "permissions" table.
 * This is a persistence model only; business rules live in the domain Permission class.
 */
@Entity
@Table(name = "permissions")
@Getter
@Setter
@NoArgsConstructor(access = AccessLevel.PROTECTED) // required by JPA
@AllArgsConstructor
public class PermissionJpaEntity {

    @Id
    @Column(name = "permission_id", nullable = false, updatable = false)
    private UUID permissionId; // generated by the domain, so no @GeneratedValue

    @Column(name = "permission_code", nullable = false, unique = true, length = 100)
    private String permissionCode;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;
}